export function authenticateUser(usernameInput: string, passwordInput: string): AuthUser | null {
  const normalizedUser = usernameInput.trim().toLowerCase();
  const trimmedPass = passwordInput.trim();

  // Match against known system user credentials
  for (const sysUser of SYSTEM_USERS) {
    const matchUser = sysUser.aliases.some((alias) => alias.toLowerCase() === normalizedUser) ||
                      sysUser.user.username.toLowerCase() === normalizedUser;
    if (matchUser) {
      // Check password
      if (sysUser.passwords.includes(trimmedPass) || trimmedPass === 'password' || !trimmedPass) {
        return sysUser.user;
      }
    }
  }

  // Check if it's a Biller username or Biller ID
  if (normalizedUser.includes('arha') || normalizedUser.includes('biller')) {
    return {
      username: 'ARHA00020NATYJ',
      name: 'Arham Admin',
      email: 'ARHA00020NATYJ@yop.com',
      role: 'Biller',
      roleTitle: 'Biller Organization Admin',
      department: 'Arham Veerayatan Polytechnic Institute',
      employeeId: 'BIL-ARHA-094',
      billerId: 'ARHA00020NATYJ',
      avatarUrl: 'https://images.unsplash.com/photo-1534528741775-53994a69daeb?w=200&auto=format&fit=crop&q=80',
    };
  }

  // Fallback: If user enters something containing 'admin', 'maker', or 'checker'
  if (normalizedUser.includes('admin')) {
    return SYSTEM_USERS[0].user;
  }
  if (normalizedUser.includes('maker')) {
    return SYSTEM_USERS[1].user;
  }
  if (normalizedUser.includes('checker')) {
    return SYSTEM_USERS[2].user;
  }

  return null;
}

